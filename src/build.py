PAGES = []  # registry for SEO.md


def finalise(s):
    s = s.replace("bp-", "jw-").replace("bpSlideUp", "jwSlideUp").replace("bpFadeIn", "jwFadeIn").replace("bpPulse", "jwPulse")
    s = s.replace("—", "-").replace("–", "-")  # no em/en dashes anywhere
    return s


def page(fname, wp_title, slug, parent, seo_title, seo_desc, kw, comps, body, schemas=(), extra_js="", form_href=None, sticky_on=True):
    css = "\n".join(C[c] for c in comps)
    sch = "\n".join(schema(s) for s in schemas)
    html = f"""<!-- wp:html -->
<!-- ============================================================
J.W ELECTRICAL INSTALLATIONS - {wp_title.upper()} PAGE
Self-contained page: paste into a single Custom HTML block.
Generated by src/build.py - edit the source and rebuild rather than editing here.
============================================================ -->
{sch}
{FONTS}
<style>{GLOBAL}</style>
<style>{css}</style>
{sticky(form_href) if sticky_on else ''}
<div class="bp-page">
{body}
</div>
{GLOBAL_JS}{extra_js}
<!-- /wp:html -->
"""
    html = finalise(html)
    with open(os.path.join(OUT, fname), "w") as f:
        f.write(html)
    PAGES.append(dict(file=fname, wp_title=wp_title, slug=slug, parent=parent, title=seo_title, desc=seo_desc, kw=kw))


